/**
 * Unified Markdown Compiler & MathJax AST Pipeline for Hoshinote
 *
 * Implements:
 * - GFM headings (h1 - h6)
 * - Fenced code blocks with language classes and HTML entity escaping
 * - Inline code
 * - GFM Task lists with disabled checkboxes
 * - GFM Tables with wikilink, escaped pipe, and inline code pipe protection
 * - Blockquotes with multiline display math DOM nesting protection
 * - Obsidian Wikilinks [[Target|Alias]]
 * - Bold, italic, strikethrough formatting
 * - Vector SVG MathJax ($formula$ and $$formula$$)
 * - Currency differentiation ($100 vs $E=mc^2$) and ranges ($100-$50, $50/$100)
 * - Escaped dollar signs (\$50 -> $50)
 * - Robust XSS sanitization (unquoted handlers, javascript: URIs, self-closing scripts)
 */

import { renderMathToSvg, escapeHtml } from './math';
import { renderWikilinksToHtml } from './remark-wikilink';
import { highlightCode } from './syntax';

export interface MarkdownOptions {
  existingTitles?: string[];
  enableWikilinks?: boolean;
}

/**
 * Sanitizes HTML against XSS vulnerabilities:
 * - Strips full and self-closing <script .../> and <iframe> tags
 * - Strips dangerous <object> and <embed> tags
 * - Strips unquoted and quoted on* event handlers (onerror=alert(1), onload=alert(1), ontoggle=alert(1))
 * - Neutralizes javascript: and vbscript: URI schemes in href, src, action, formaction
 * - Preserves legitimate SVG elements and attributes generated by MathJax
 */
export function sanitizeHtml(html: string): string {
  let s = html;
  // 1. Strip script tags (both <script>...</script> and self-closing <script .../>)
  s = s.replace(/<script\b[^>]*\/>|<script\b[^>]*>[\s\S]*?(?:<\/script\s*>|$)/gi, '');
  // 2. Strip iframe tags
  s = s.replace(/<iframe\b[^>]*\/>|<iframe\b[^>]*>[\s\S]*?(?:<\/iframe\s*>|$)/gi, '');
  // 3. Strip object, embed tags
  s = s.replace(/<object\b[^>]*\/>|<object\b[^>]*>[\s\S]*?(?:<\/object\s*>|$)/gi, '');
  s = s.replace(/<embed\b[^>]*\/>|<embed\b[^>]*>[\s\S]*?(?:<\/embed\s*>|$)/gi, '');
  // 4. Strip event handlers (on..., quoted or unquoted)
  s = s.replace(/[\s/]+on[a-zA-Z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, '');
  s = s.replace(/[\s/]+on[a-zA-Z]+(?=[\s/>])/gi, '');
  // 5. Neutralize javascript: / vbscript: URI schemes in href/src
  s = s.replace(
    /([\s/]+(?:href|src|action|formaction)\s*=\s*)(?:"[\s\u0000-\u0020]*(?:javascript|vbscript):[^"]*"|'[\s\u0000-\u0020]*(?:javascript|vbscript):[^']*'|[\s\u0000-\u0020]*(?:javascript|vbscript):[^\s>]*)/gi,
    '$1"#" '
  );
  return s;
}

/**
 * Splits table cells by '|' while protecting:
 * - Pipes enclosed in '[[...]]' wikilinks
 * - Escaped pipes '\|'
 * - Pipes enclosed in inline code backticks '`...`'
 */
function splitTableCells(line: string): string[] {
  let inner = line.trim();
  if (inner.startsWith('|')) inner = inner.slice(1);
  if (inner.endsWith('|')) inner = inner.slice(0, -1);

  const cells: string[] = [];
  let current = '';
  let inWikilink = false;
  let inCode = false;

  for (let i = 0; i < inner.length; i++) {
    if (inner[i] === '\\' && inner[i + 1] === '|') {
      current += '|';
      i++;
    } else if (inner[i] === '`') {
      inCode = !inCode;
      current += '`';
    } else if (inner[i] === '[' && inner[i + 1] === '[') {
      inWikilink = true;
      current += '[[';
      i++;
    } else if (inner[i] === ']' && inner[i + 1] === ']') {
      inWikilink = false;
      current += ']]';
      i++;
    } else if (inner[i] === '|' && !inWikilink && !inCode) {
      cells.push(current.trim());
      current = '';
    } else {
      current += inner[i];
    }
  }
  cells.push(current.trim());
  return cells;
}

/**
 * Renders GFM tables while protecting wikilink pipes, escaped pipes, and code pipes in cells.
 */
/**
 * Table delimiter regex constructed via RegExp to prevent Tailwind JIT scanner
 * from misinterpreting `[-:` as an arbitrary CSS property utility.
 */
const TABLE_DELIMITER_REGEX = new RegExp('^\\|[\\s|:-]+\\|$');

function renderTables(text: string): string {
  const lines = text.split('\n');
  let inTable = false;
  let tableHtml = '';
  const output: string[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith('|') && line.endsWith('|')) {
      const cells = splitTableCells(line);
      if (!inTable) {
        inTable = true;
        tableHtml = '<table><thead><tr>' + cells.map((c) => `<th>${c}</th>`).join('') + '</tr></thead><tbody>';
        // Skip delimiter line if present (| --- | --- |)
        if (i + 1 < lines.length && TABLE_DELIMITER_REGEX.test(lines[i + 1].trim())) {
          i++;
        }
      } else {
        tableHtml += '<tr>' + cells.map((c) => `<td>${c}</td>`).join('') + '</tr>';
      }
    } else {
      if (inTable) {
        inTable = false;
        tableHtml += '</tbody></table>';
        output.push(tableHtml);
      }
      output.push(lines[i]);
    }
  }

  if (inTable) {
    tableHtml += '</tbody></table>';
    output.push(tableHtml);
  }

  return output.join('\n');
}

/**
 * Groups consecutive blockquote lines ('> quote') and renders their inner content
 * with proper DOM hierarchy balancing.
 */
function processBlockquotes(text: string, renderInner: (s: string) => string): string {
  const lines = text.split('\n');
  const result: string[] = [];
  let bqLines: string[] = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const match = line.match(/^>\s?(.*)$/);
    if (match) {
      bqLines.push(match[1]);
    } else {
      if (bqLines.length > 0) {
        result.push(`<blockquote><p>${renderInner(bqLines.join('\n'))}</p></blockquote>`);
        bqLines = [];
      }
      result.push(line);
    }
  }
  if (bqLines.length > 0) {
    result.push(`<blockquote><p>${renderInner(bqLines.join('\n'))}</p></blockquote>`);
  }
  return result.join('\n');
}

/**
 * Inner markdown transformations (headings, task lists, tables, wikilinks, bold, italic).
 */
function transformMarkdownInner(input: string, existingTitles?: string[]): string {
  let html = input;

  // 1. Headings (# h1 to ###### h6)
  html = html.replace(/^###### (.*$)/gim, '<h6>$1</h6>');
  html = html.replace(/^##### (.*$)/gim, '<h5>$1</h5>');
  html = html.replace(/^#### (.*$)/gim, '<h4>$1</h4>');
  html = html.replace(/^### (.*$)/gim, '<h3>$1</h3>');
  html = html.replace(/^## (.*$)/gim, '<h2>$1</h2>');
  html = html.replace(/^# (.*$)/gim, '<h1>$1</h1>');

  // 2. GFM Task lists (- [ ] or - [x])
  html = html.replace(
    /^[*-] \[ \]\s+(.*)$/gim,
    '<li class="task-list-item"><input type="checkbox" disabled /> $1</li>'
  );
  html = html.replace(
    /^[*-] \[x\]\s+(.*)$/gim,
    '<li class="task-list-item"><input type="checkbox" checked disabled /> $1</li>'
  );

  // 3. GFM Tables
  html = renderTables(html);

  // 4. Wikilinks [[Target|Alias]]
  html = renderWikilinksToHtml(html, existingTitles);

  // 5. Images: ![alt](url)
  html = html.replace(/!\[([^\]]*)\]\(([^)]+)\)/g, '<img src="$2" alt="$1" loading="lazy" />');

  // 6. Standard Links: [text](url) (excluding images already converted)
  html = html.replace(/(^|[^\\])\[([^\]]+)\]\(([^)]+)\)/g, '$1<a href="$3" target="_blank" rel="noopener noreferrer">$2</a>');

  // 7. Bold, Italic, Strikethrough
  html = html.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/(^|[^a-zA-Z0-9_])__([^_]+)__(?![a-zA-Z0-9_])/g, '$1<strong>$2</strong>');
  html = html.replace(/\*([^*]+)\*/g, '<em>$1</em>');
  html = html.replace(/(^|[^a-zA-Z0-9_])_([^_]+)_(?![a-zA-Z0-9_])/g, '$1<em>$2</em>');
  html = html.replace(/~~([^~]+)~~/g, '<del>$1</del>');

  // 8. Unordered Lists (- or *)
  html = html.replace(/^[*-]\s+(?!\[[ x]\])(.*)$/gim, '<li>$1</li>');

  return html;
}

/**
 * Renders raw Markdown into sanitized HTML using Token Shielding.
 */
export function renderMarkdown(markdown: string | null | undefined, existingTitles?: string[]): string {
  if (markdown === null || markdown === undefined) return '';
  if (typeof markdown !== 'string' || markdown.trim().length === 0) return '';

  const tokens: string[] = [];

  // Phase 1: Shield Fenced Code Blocks (```lang\ncode\n```) with header, language badge, copy button, and syntax highlighting
  let text = markdown.replace(/```([a-zA-Z0-9_-]*)\r?\n([\s\S]*?)```/gm, (_match, lang, code) => {
    const rawTrimmed = code.trim();
    const normalizedLang = (lang || '').toLowerCase();

    if (normalizedLang === 'graph') {
      const encoded = encodeURIComponent(rawTrimmed);
      const rendered = `<div class="hoshinote-embedded-graph" data-graph-source="${encoded}"></div>`;
      const idx = tokens.length;
      tokens.push(rendered);
      return `___HOSHINOTE_TOKEN_${idx}___`;
    }

    if (normalizedLang === 'mermaid') {
      const encoded = encodeURIComponent(rawTrimmed);
      const rendered = `<div class="hoshinote-embedded-mermaid" data-mermaid-source="${encoded}"></div>`;
      const idx = tokens.length;
      tokens.push(rendered);
      return `___HOSHINOTE_TOKEN_${idx}___`;
    }

    const safeCode = highlightCode(rawTrimmed, lang);
    const displayLang = lang ? lang.toUpperCase() : 'TEXT';
    const langClass = lang ? ` class="language-${lang}"` : '';
    const rendered = `<div class="codeblock-wrapper"><div class="codeblock-header"><span class="codeblock-lang">${displayLang}</span><button class="codeblock-copy-btn" type="button" aria-label="Copy code">Copy</button></div><pre><code${langClass}>${safeCode}</code></pre></div>`;
    const idx = tokens.length;
    tokens.push(rendered);
    return `___HOSHINOTE_TOKEN_${idx}___`;
  });

  // Phase 2: Shield Inline Code Spans (`code`)
  text = text.replace(/`([^`\r\n]+)`/g, (_match, code) => {
    const rendered = `<code>${escapeHtml(code)}</code>`;
    const idx = tokens.length;
    tokens.push(rendered);
    return `___HOSHINOTE_TOKEN_${idx}___`;
  });

  // Phase 3: Blockquotes
  text = processBlockquotes(text, (inner) => {
    return transformMarkdownInner(inner, existingTitles);
  });

  // Phase 4: Outer Markdown transformations
  text = transformMarkdownInner(text, existingTitles);

  // Phase 5: Restore Tokens in reverse index order
  for (let i = tokens.length - 1; i >= 0; i--) {
    text = text.replace(`___HOSHINOTE_TOKEN_${i}___`, tokens[i]);
  }

  // Phase 6: Robust Sanitization
  return sanitizeHtml(text);
}

/**
 * Parses markdown with embedded LaTeX math expressions into sanitized HTML with vector SVGs.
 * Distinguishes currency amounts ($100, $200, $100-$50) from formulas ($E=mc^2$) and handles escaped dollars (\$50).
 */
export function parseMarkdownWithMath(content: string | null | undefined, existingTitles?: string[]): string {
  if (content === null || content === undefined) return '';
  if (typeof content !== 'string' || content.trim().length === 0) return '';

  const mathTokens: string[] = [];

  // 1. Protect escaped dollar signs: \$50 -> placeholder token
  const ESCAPED_DOLLAR_PLACEHOLDER = '___HOSHINOTE_ESCAPED_DOLLAR___';
  let processed = content.replace(/\\\$/g, ESCAPED_DOLLAR_PLACEHOLDER);

  // 2. Shield Fenced Code Blocks & Inline Code so math inside code blocks is never matched
  const codeTokens: string[] = [];
  processed = processed.replace(/```([a-zA-Z0-9_-]*)\r?\n([\s\S]*?)```/gm, (_match, lang, code) => {
    const idx = codeTokens.length;
    codeTokens.push(`\`\`\`${lang}\n${code}\`\`\``);
    return `___HOSHINOTE_RAW_CODE_${idx}___`;
  });
  processed = processed.replace(/`([^`\r\n]+)`/g, (_match, code) => {
    const idx = codeTokens.length;
    codeTokens.push(`\`${code}\``);
    return `___HOSHINOTE_RAW_CODE_${idx}___`;
  });

  // 3. Block display math inside or outside blockquotes ($$formula$$)
  processed = processed.replace(/\$\$([\s\S]+?)\$\$/g, (_match, formula) => {
    // If inside blockquote, strip leading '> ' or '>' from formula lines
    const cleanFormula = formula
      .split('\n')
      .map((line: string) => line.replace(/^>\s?/, ''))
      .join('\n');
    const rendered = renderMathToSvg(cleanFormula, true);
    const idx = mathTokens.length;
    mathTokens.push(rendered);
    return `___HOSHINOTE_MATH_${idx}___`;
  });

  // 4. Currency protection before inline math (supports ranges $100-$50, $50/$100, $5,$10)
  // Ensures inline math expressions beginning with numbers (e.g. $2 \times 2$, $10^{-5}$, $3.14 \text{ rad}$, $1/2$)
  // are NOT falsely captured as currency amounts.
  const currencyTokens: string[] = [];
  const CURRENCY_REGEX = /(^|[^\w\\])\$(\d{1,3}(?:,\d{3})*(?:\.\d+)?|\d+(?:\.\d+)?)(?=[^\w$]|$)/g;
  processed = processed.replace(CURRENCY_REGEX, (match, prefix, amount, offset, fullText) => {
    const dollarIdx = offset + prefix.length;
    const remainder = fullText.slice(dollarIdx);

    // Check if this '$' is the start of a valid inline math span ($formula$)
    const mathMatch = remainder.match(/^\$([^\s$][^$\r\n]*?[^\s$]|\S)\$/);
    if (mathMatch) {
      const formula = mathMatch[1];
      const afterClosingDollar = remainder.slice(mathMatch[0].length);

      // Distinguish genuine currency ranges (e.g. "$100-$50", "$1-$2", "$50/$100", "$5,$10")
      // In currency ranges, the inner formula is solely an amount followed by a separator (-, /, ,),
      // and the closing '$' is immediately followed by another currency amount (\$\d).
      const isCurrencyRange =
        /^\d+(?:,\d{3})*(?:\.\d+)?[-/,]+$/.test(formula) && /^\d/.test(afterClosingDollar);

      if (!isCurrencyRange) {
        // Valid math formula starting with a number — do NOT capture as currency.
        return match;
      }
    }

    const idx = currencyTokens.length;
    currencyTokens.push(`$${amount}`);
    return `${prefix}___HOSHINOTE_CURRENCY_${idx}___`;
  });

  // 5. Inline math: $formula$
  processed = processed.replace(/(^|[^\\])\$([^\s$][^$]*?[^\s$]|\S)\$/g, (_match, prefix, formula) => {
    const rendered = renderMathToSvg(formula, false);
    const idx = mathTokens.length;
    mathTokens.push(rendered);
    return `${prefix}___HOSHINOTE_MATH_${idx}___`;
  });

  // 6. Restore currency tokens
  for (let i = 0; i < currencyTokens.length; i++) {
    processed = processed.replace(`___HOSHINOTE_CURRENCY_${i}___`, () => currencyTokens[i]);
  }

  // 7. Restore raw code blocks
  for (let i = 0; i < codeTokens.length; i++) {
    processed = processed.replace(`___HOSHINOTE_RAW_CODE_${i}___`, codeTokens[i]);
  }

  // 8. Restore escaped dollars
  processed = processed.replace(new RegExp(ESCAPED_DOLLAR_PLACEHOLDER, 'g'), '$');

  // 9. Render markdown (wikilinks, code blocks, tables, blockquotes)
  let html = renderMarkdown(processed, existingTitles);

  // 10. Restore math tokens (ensures wikilinks in math SVGs are not converted to <a> tags)
  for (let i = 0; i < mathTokens.length; i++) {
    html = html.replace(`___HOSHINOTE_MATH_${i}___`, mathTokens[i]);
  }

  return html;
}
